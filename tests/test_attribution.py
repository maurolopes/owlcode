"""No agent attribution in a commit message or a pull request's text (AGENTS.md "Rules"): .github/attribution.sh holds
the patterns that the commit-msg hook runs on every commit and the gates workflow's job `changes` on a pull request's own
commits. The workflow `attribution` removes the lines from the text at its opening and at each edit, with main's copy of the patterns. It
refuses only the shapes a harness writes, never prose that names an agent or a link."""

import os
import re
import shutil
import subprocess
from pathlib import Path

import pytest
import yaml

REPO = Path(__file__).resolve().parents[1]
CHECK = REPO / ".github" / "attribution.sh"
HOOK = REPO / ".githooks" / "commit-msg"

# Commits on main that carry an attribution line: they came before the guard and a pushed commit never changes.
# Each one among the 200 commits up to PINNED must be refused, and no other commit. PINNED is a fixed commit of main, so a
# commit that lands later (a bypass merge with such a line) cannot fail the test on main.
KNOWN = {"60c9e01", "2dec409", "8d75691", "bfc8652", "0f44223", "de3e188"}
PINNED = "2c4f5b67431071e6b25cb2ce9f590808b5f782be"


def check(text: str, name: str = "") -> subprocess.CompletedProcess[str]:
    return subprocess.run(["sh", str(CHECK), *([name] if name else [])], input=text, capture_output=True, text=True, check=False)


@pytest.mark.parametrize("line", [
    "Claude-Session: https://claude.ai/code/session_01NPZ5VFX84ZEkMyhiFUf3mR",
    "claude-session: anything",
    "Co-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>",
    "Co-authored-by: Claude <noreply@anthropic.com>",
    "Co-authored-by: Someone <noreply@anthropic.com>",
    "Co-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>",
    "  Co-Authored-By: Codex <codex@openai.com>",
    "Co-authored-by: Cursor Agent <cursoragent@cursor.com>",
    "Co-authored-by: aider (gpt-4o) <noreply@aider.chat>",
    "Co-authored-by: devin-ai-integration[bot] <158243242+devin-ai-integration[bot]@users.noreply.github.com>",
    "See https://claude.ai/code/session_01XgATpDWEWZ3QUaMeDEF8Bi for the session.",
    "\N{ROBOT FACE} Generated with [Claude Code](https://claude.com/claude-code)",
    "Generated with [Claude Code](https://claude.ai/code)",
])
def test_each_attribution_shape_is_refused(line: str) -> None:
    refused = check(f"ABC-1: a change\n\nWhat changed and why.\n{line}\n")
    assert refused.returncode == 1, line
    assert refused.stdout == f"line 4: {line}\n"


@pytest.mark.parametrize("line", [
    "The change was co-authored by Claude in a session, the owner says.",
    "Co-authored-by: Jane Doe <jane@example.org>",
    # a person whose name is an agent's: the address decides
    "Co-authored-by: Claude Dupont <cd@example.fr>",
    "Co-authored-by: Kim Aider <kim@example.org>",
    "Co-authored-by: Devin Smith <devin.smith@example.org>",
    "AGENTS.md forbids a `Claude-Session:` line and a `Co-Authored-By:` trailer.",
    "- the `Claude-Session:` line that the harness asks for",
    "The link claude.ai/code/session_ is a session link, without its scheme here.",
    "The model writes https://claude.ai/code in its footer.",
    "Generated with Claude Code, the owner says, then checked by hand.",
    "logo: the mark, generated by the owner in Gemini from docs/logo-prompt.md",
    "Claude reviewed it; see https://github.com/acme/product/pull/131.",
])
def test_prose_that_names_an_agent_or_a_link_passes(line: str) -> None:
    passed = check(f"ABC-1: a change\n\n{line}\n")
    assert passed.returncode == 0 and passed.stdout == "", line


def strip(text: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(["sh", str(CHECK), "--strip"], input=text, capture_output=True, text=True, check=False)


def test_strip_prints_the_text_without_the_attribution_lines() -> None:
    """The workflow `attribution` writes this text back to the pull request."""
    one = strip("## What\n\nA change.\n\nhttps://claude.ai/code/session_01abc\n")
    assert one.returncode == 0 and one.stdout == "## What\n\nA change.\n\n", one.stdout + one.stderr
    two = strip("A change.\nClaude-Session: https://claude.ai/code/session_01abc\nCo-authored by Claude, in prose.\n"
                "\N{ROBOT FACE} Generated with [Claude Code](https://claude.com/claude-code)\n")
    assert two.returncode == 0 and two.stdout == "A change.\nCo-authored by Claude, in prose.\n", "prose stays"
    none = strip("A change.\n\nNo such line.\n")
    assert none.returncode == 0 and none.stdout == "A change.\n\nNo such line.\n"
    crlf = strip("A change.\r\n\r\nhttps://claude.ai/code/session_01abc\r\n")
    assert crlf.returncode == 0 and crlf.stdout == "A change.\n\n", "the CR goes, as in the check"
    only = strip("https://claude.ai/code/session_01abc\n")
    assert only.returncode == 0 and only.stdout == "", "a text of one such line becomes empty, and that is no failure"
    assert strip("").returncode == 0


def test_a_pull_request_text_with_crlf_line_ends_names_the_text_and_the_line() -> None:
    """GitHub sends a pull request's text with CRLF line ends; the name comes first in each line found."""
    refused = check("## What and why\r\n\r\nA change.\r\n\r\nhttps://claude.ai/code/session_01abc\r\n", "the pull request's text")
    assert refused.returncode == 1 and refused.stdout == "the pull request's text, line 5: https://claude.ai/code/session_01abc\n"
    assert check("").returncode == 0


def env_for_git(tmp_path: Path) -> dict[str, str]:
    return {**os.environ, "HOME": str(tmp_path), "GIT_CONFIG_NOSYSTEM": "1", "GIT_AUTHOR_NAME": "t", "GIT_AUTHOR_EMAIL": "t@example.org",
            "GIT_COMMITTER_NAME": "t", "GIT_COMMITTER_EMAIL": "t@example.org"}


@pytest.fixture
def repo(tmp_path: Path) -> tuple[Path, dict[str, str]]:
    """A clone's view: the tracked hooks and the pattern file at their places, and `core.hooksPath` set as `mise run hooks` sets it."""
    where, env = tmp_path / "repo", env_for_git(tmp_path)
    subprocess.run(["git", "init", "-q", "-b", "work", str(where)], env=env, check=True)
    for path in (HOOK, CHECK):
        (where / path.parent.name).mkdir(exist_ok=True)
        shutil.copy2(path, where / path.parent.name / path.name)
    subprocess.run(["git", "-C", str(where), "config", "core.hooksPath", ".githooks"], env=env, check=True)
    subprocess.run(["git", "-C", str(where), "config", "commit.gpgsign", "false"], env=env, check=True)
    return where, env


def commit(repo: tuple[Path, dict[str, str]], message: str) -> subprocess.CompletedProcess[str]:
    where, env = repo
    (where / "file.txt").write_text(message)
    subprocess.run(["git", "-C", str(where), "add", "-A"], env=env, check=True)
    return subprocess.run(["git", "-C", str(where), "commit", "-q", "-F", "-"], input=message, env=env,
                          capture_output=True, text=True, check=False)


def test_the_hook_is_tracked_as_executable() -> None:
    """git runs a hook only when it can execute it: with that, `mise run hooks` (core.hooksPath) needs no step again."""
    assert os.access(HOOK, os.X_OK) and os.access(CHECK, os.X_OK)
    mode = subprocess.run(["git", "-C", str(REPO), "ls-files", "-s", ".githooks/commit-msg"], capture_output=True, text=True, check=True).stdout
    assert mode.startswith("100755 "), mode


def test_the_hook_refuses_a_commit_with_a_session_line(repo: tuple[Path, dict[str, str]]) -> None:
    refused = commit(repo, "ABC-1: a change\n\nWhat changed.\n\nClaude-Session: https://claude.ai/code/session_01abc\n")
    said = refused.stdout + refused.stderr  # git sends a hook's output to its stderr
    assert refused.returncode == 1, said
    assert "the commit message, line 5: Claude-Session: https://claude.ai/code/session_01abc" in said and 'AGENTS.md "Rules"' in said
    log = subprocess.run(["git", "-C", str(repo[0]), "log", "--oneline"], env=repo[1], capture_output=True, text=True, check=False)
    assert log.stdout == "", "nothing was committed"


def test_the_hook_refuses_a_comment_line_that_git_commit_m_keeps(repo: tuple[Path, dict[str, str]]) -> None:
    """`git commit -m` keeps a line that starts with `#` (its clean-up is `whitespace`), so the hook
    reads the comment lines too."""
    where, env = repo
    refused = subprocess.run(["git", "-C", str(where), "commit", "-q", "--allow-empty", "-m", "ABC-1: a change",
                              "-m", "# https://claude.ai/code/session_01abc"], env=env, capture_output=True, text=True, check=False)
    assert refused.returncode == 1, refused.stdout + refused.stderr
    log = subprocess.run(["git", "-C", str(where), "log", "--oneline"], env=env, capture_output=True, text=True, check=False)
    assert log.stdout == "", "nothing was committed"


def test_the_hook_cuts_the_diff_with_another_comment_character(repo: tuple[Path, dict[str, str]]) -> None:
    """Git starts the scissors line with core.commentChar, so a `;` must cut the diff as `#` does."""
    where, env = repo
    subprocess.run(["git", "-C", str(where), "config", "core.commentChar", ";"], env=env, check=True)
    (where / "file.txt").write_text("Claude-Session: https://claude.ai/code/session_01abc\n")
    subprocess.run(["git", "-C", str(where), "add", "-A"], env=env, check=True)
    editor = {**env, "GIT_EDITOR": "sed -i.bak '1s/^/ABC-1: a change/'"}
    verbose = subprocess.run(["git", "-C", str(where), "commit", "-q", "-v"], env=editor, capture_output=True, text=True, check=False)
    assert verbose.returncode == 0, verbose.stdout + verbose.stderr


def test_the_hook_passes_a_normal_message_and_reads_no_diff(repo: tuple[Path, dict[str, str]]) -> None:
    """git hands the hook the diff of `git commit -v` below the scissors line: it never reaches the commit, so a file whose
    text holds a session line can still be committed."""
    ok = commit(repo, "ABC-1: a change\n\nThe change was co-authored by Claude in prose; the `Co-Authored-By:` trailer is refused.\n")
    assert ok.returncode == 0, ok.stdout + ok.stderr
    where, env = repo
    (where / "file.txt").write_text("Claude-Session: https://claude.ai/code/session_01abc\n")
    (where.parent / "template").write_text("\n# a comment line of the template\n")
    subprocess.run(["git", "-C", str(where), "add", "-A"], env=env, check=True)
    editor = {**env, "GIT_EDITOR": "sed -i.bak '1s/^/ABC-1: more/'"}
    verbose = subprocess.run(["git", "-C", str(where), "commit", "-q", "-v", "-t", str(where.parent / "template")], env=editor,
                             capture_output=True, text=True, check=False)
    assert verbose.returncode == 0, verbose.stdout + verbose.stderr
    body = subprocess.run(["git", "-C", str(where), "log", "-1", "--format=%B"], env=env, capture_output=True, text=True, check=True)
    assert body.stdout.strip() == "ABC-1: more"


def test_the_messages_on_main_pass_but_the_known_attribution_lines() -> None:
    """The 200 commits up to PINNED (CI fetches the whole history for this test): only the commits that carry a real attribution line are
    refused, so the patterns catch no ordinary message of this repository. A copy without that history (a shallow clone)
    skips."""
    has_pin = subprocess.run(["git", "-C", str(REPO), "cat-file", "-e", f"{PINNED}^{{commit}}"], capture_output=True, check=False)
    if has_pin.returncode != 0:
        pytest.skip("the history up to PINNED is not in this clone (the date sweep's copy, or a shallow clone)")
    log = subprocess.run(["git", "-C", str(REPO), "log", "-200", "--format=%x1e%h%n%B", PINNED], capture_output=True, text=True, check=True).stdout
    messages = [m.split("\n", 1) for m in log.split("\x1e")[1:]]
    assert len(messages) == 200, "a shallow clone: fetch the whole history (gates.yml, the job `python`)"
    text, owner = "", []
    for sha, body in messages:
        lines = body.split("\n")  # as grep splits: str.splitlines() also splits on \v, \f and U+2028 (R1-4)
        text += "\n".join(lines) + "\n"
        owner += [sha[:7]] * len(lines)
    found = check(text)
    refused = {owner[int(line.split()[1].rstrip(":")) - 1] for line in found.stdout.splitlines()}
    assert refused == KNOWN & {sha[:7] for sha, _ in messages}, found.stdout


TEXT_CHECK = REPO / ".github" / "workflows" / "attribution.yml"


def test_the_text_check_runs_mains_script_and_needs_a_key_only_to_clean() -> None:
    """The workflow `attribution` runs on `pull_request_target`, so GitHub runs main's copy of this file, never a
    branch's, and only when the text can change: at the opening and at an edit. It checks out `.github/attribution.sh`
    from the base commit with no credentials, reads no other repository, and makes the implementer app's token only
    when the script finds a line (pull requests write, checks read)."""
    flow = yaml.safe_load(TEXT_CHECK.read_text())
    on = flow[True]  # YAML 1.1 reads the key `on` as true
    assert set(on) == {"pull_request_target"}
    assert sorted(on["pull_request_target"]["types"]) == ["edited", "opened"]
    assert flow["permissions"] == {"contents": "read"}
    assert set(flow["jobs"]) == {"attribution"}
    steps = flow["jobs"]["attribution"]["steps"]
    checkout = steps[0]["with"]
    assert checkout["ref"] == "${{ github.sha }}" and checkout["persist-credentials"] is False
    assert checkout["sparse-checkout"].split() == [".github/attribution.sh", ".github/attribution-clean.sh"] and "repository" not in checkout
    token = next(s for s in steps if s.get("id") == "token")
    assert token["if"] == "steps.find.outputs.found == 'true'"
    assert {k: v for k, v in token["with"].items() if k.startswith("permission-")} == \
        {"permission-pull-requests": "write", "permission-checks": "read"}
    keyed = [s.get("id") or s.get("name") for s in steps if "secrets." in yaml.safe_dump(s)]
    assert keyed == ["token"], keyed


def test_the_products_config_names_the_rule_of_this_repository() -> None:
    """The called workflow reads `.workflow.toml` from main and names `[attribution] rule` in its log."""
    import tomllib
    config = tomllib.loads((REPO / ".workflow.toml").read_text())
    assert config == {"attribution": {"rule": 'AGENTS.md "Rules"'}}
    assert '## Rules' in (REPO / "AGENTS.md").read_text(), "the rule's section exists under that name"


def test_no_workflow_calls_a_workflow_of_the_owners_other_repositories() -> None:
    """A public repository cannot call a private repository's workflow, and this repository runs on its own: no `uses:`
    names a repository of the owner."""
    found = [f"{path.name}: {line.strip()}" for path in sorted((REPO / ".github" / "workflows").glob("*.y*ml"))
             for line in path.read_text().splitlines() if re.search(r"uses:\s*maurolopes/", line)]
    assert found == []
